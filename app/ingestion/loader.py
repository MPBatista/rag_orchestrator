import os
import pdfplumber
import docx
import csv
import hashlib
from bs4 import BeautifulSoup
from pptx import Presentation
from ebooklib import epub
import re
import unicodedata

# extensões suportadas
VALID_EXTENSIONS = {
    ".txt", ".md", ".markdown", ".pdf", ".docx",
    ".html", ".htm", ".csv", ".json", ".epub", ".pptx"
}


# =========================================================
# 🔍 DETECÇÃO DE BINÁRIO
# =========================================================
def is_binary_file(path: str) -> bool:
    try:
        with open(path, "rb") as f:
            chunk = f.read(2048)
            return b"\x00" in chunk
    except:
        return True


# =========================================================
# 🧹 NORMALIZAÇÃO E LIMPEZA
# =========================================================
def clean_text(text: str) -> str:
    if not text:
        return ""

    # normalizar unicode
    text = unicodedata.normalize("NFKC", text)

    # remover múltiplos espaços
    text = re.sub(r"\s+", " ", text)

    # remover boilerplate comum
    boilerplate_patterns = [
        r"Page \d+ of \d+",
        r"Copyright.*\d{4}",
        r"All rights reserved",
        r"Este documento.*",
        r"Generated by.*",
    ]
    for pattern in boilerplate_patterns:
        text = re.sub(pattern, "", text, flags=re.IGNORECASE)

    return text.strip()


# =========================================================
# 🔑 HASHING PARA DEDUPLICAÇÃO
# =========================================================
def compute_hash(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


# =========================================================
# 📄 LOADERS ESPECÍFICOS
# =========================================================

def load_txt(path: str) -> str:
    with open(path, "r", encoding="utf-8", errors="ignore") as fp:
        return fp.read()


def load_pdf(path: str) -> str:
    text = []
    try:
        with pdfplumber.open(path) as pdf:
            for page in pdf.pages:
                extracted = page.extract_text()
                if extracted:
                    text.append(extracted)
    except Exception as e:
        print(f"[loader] Erro ao ler PDF {path}: {e}")
    return "\n".join(text)


def load_docx(path: str) -> str:
    try:
        doc = docx.Document(path)
        return "\n".join([p.text for p in doc.paragraphs])
    except Exception as e:
        print(f"[loader] Erro ao ler DOCX {path}: {e}")
        return ""


def load_html(path: str) -> str:
    try:
        with open(path, "r", encoding="utf-8", errors="ignore") as fp:
            soup = BeautifulSoup(fp.read(), "html.parser")
            return soup.get_text(separator="\n")
    except Exception as e:
        print(f"[loader] Erro ao ler HTML {path}: {e}")
        return ""


def load_markdown(path: str) -> str:
    return load_txt(path)


def load_csv(path: str) -> str:
    rows = []
    try:
        with open(path, "r", encoding="utf-8", errors="ignore") as fp:
            reader = csv.reader(fp)
            for row in reader:
                rows.append(" | ".join(row))
    except Exception as e:
        print(f"[loader] Erro ao ler CSV {path}: {e}")
    return "\n".join(rows)


def load_epub(path: str) -> str:
    try:
        book = epub.read_epub(path)
        text = []
        for item in book.get_items():
            if item.get_type() == epub.ITEM_DOCUMENT:
                soup = BeautifulSoup(item.get_body_content(), "html.parser")
                text.append(soup.get_text(separator="\n"))
        return "\n".join(text)
    except Exception as e:
        print(f"[loader] Erro ao ler EPUB {path}: {e}")
        return ""


def load_pptx(path: str) -> str:
    try:
        prs = Presentation(path)
        text = []
        for slide in prs.slides:
            for shape in slide.shapes:
                if hasattr(shape, "text"):
                    text.append(shape.text)
        return "\n".join(text)
    except Exception as e:
        print(f"[loader] Erro ao ler PPTX {path}: {e}")
        return ""


# =========================================================
# 🧠 DISPATCHER
# =========================================================
def load_file(path: str) -> str:
    ext = os.path.splitext(path)[1].lower()

    if ext in {".txt", ".md", ".markdown", ".json"}:
        return load_txt(path)

    if ext == ".pdf":
        return load_pdf(path)

    if ext == ".docx":
        return load_docx(path)

    if ext in {".html", ".htm"}:
        return load_html(path)

    if ext == ".csv":
        return load_csv(path)

    if ext == ".epub":
        return load_epub(path)

    if ext == ".pptx":
        return load_pptx(path)

    return ""


# =========================================================
# 📁 LOADER PRINCIPAL
# =========================================================
def load_documents_recursive(folder):
    docs = []

    for root, _, files in os.walk(folder):
        for f in files:
            path = os.path.join(root, f)
            ext = os.path.splitext(f)[1].lower()

            if ext not in VALID_EXTENSIONS:
                print(f"[loader] Ignorando {path} (extensão não suportada)")
                continue

            if is_binary_file(path) and ext not in {".pdf", ".docx", ".epub", ".pptx"}:
                print(f"[loader] Ignorando {path} (binário)")
                continue

            content = load_file(path)
            content = clean_text(content)

            if not content:
                print(f"[loader] Ignorando {path} (vazio ou ilegível)")
                continue

            docs.append((path, content, compute_hash(content)))

    return docs
